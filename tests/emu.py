#!/usr/bin/env python3
"""
emu.py - Runs a PE64 .exe generated by adac inside the Unicorn emulator,
simulating the KERNEL32.DLL functions the program imports.
It validates the machine code without needing Windows.
"""
import sys, struct
import pefile
from unicorn import *
from unicorn.x86_const import *
from capstone import Cs, CS_ARCH_X86, CS_MODE_64

STACK_TOP = 0x7ff00000 + 0x800000
HEAP_BASE = 0x20000000
STUB_BASE = 0x7e000000


class Result:
    def __init__(self):
        self.stdout = b""
        self.stderr = b""
        self.exit_code = None
        self.heap_live = 0
        self.heap_allocs = 0
        self.heap_frees = 0
        self.insns = 0
        self.error = None


def run_pe(path, stdin=b"", max_insns=3_000_000_000, check_align=True):
    pe = pefile.PE(path)
    base = pe.OPTIONAL_HEADER.ImageBase
    size = (pe.OPTIONAL_HEADER.SizeOfImage + 0xFFF) & ~0xFFF
    uc = Uc(UC_ARCH_X86, UC_MODE_64)
    uc.mem_map(base, size, UC_PROT_ALL)
    uc.mem_write(base, pe.header[: pe.OPTIONAL_HEADER.SizeOfHeaders])
    for s in pe.sections:
        uc.mem_write(base + s.VirtualAddress, s.get_data())
    uc.mem_map(STACK_TOP - 0x800000, 0x800000, UC_PROT_ALL)
    uc.mem_map(HEAP_BASE, 0x20000000, UC_PROT_ALL)      # 512 MB, filled on demand
    uc.mem_map(STUB_BASE, 0x1000, UC_PROT_ALL)

    res = Result()
    heap = {"next": HEAP_BASE + 0x1000, "blocks": {}}
    stdin_buf = bytearray(stdin)

    # IAT: fill every slot with a stub
    imports = {}
    for entry in pe.DIRECTORY_ENTRY_IMPORT:
        for i, imp in enumerate(entry.imports):
            name = imp.name.decode()
            stub = STUB_BASE + len(imports) * 16
            uc.mem_write(imp.address - base + base, struct.pack("<Q", stub))
            imports[stub] = name

    def arg(n):
        regs = [UC_X86_REG_RCX, UC_X86_REG_RDX, UC_X86_REG_R8, UC_X86_REG_R9]
        if n < 4:
            return uc.reg_read(regs[n])
        rsp = uc.reg_read(UC_X86_REG_RSP)
        return struct.unpack("<Q", uc.mem_read(rsp + 8 + 8 * n, 8))[0]   # [rsp]=ret, +8.. shadow(32) => arg4 em rsp+40

    def api(name):
        rsp = uc.reg_read(UC_X86_REG_RSP)
        if check_align and (rsp + 8) % 16 != 0:
            raise RuntimeError(f"misaligned stack when calling {name}: rsp=0x{rsp:x}")
        ret = 1
        if name == "ExitProcess":
            res.exit_code = arg(0) & 0xFFFFFFFF
            uc.emu_stop()
            return
        elif name == "GetStdHandle":
            ret = {(-10) & 0xFFFFFFFF: 1, (-11) & 0xFFFFFFFF: 2, (-12) & 0xFFFFFFFF: 3}[arg(0) & 0xFFFFFFFF]
        elif name == "WriteFile":
            h, buf, n, pw = arg(0), arg(1), arg(2) & 0xFFFFFFFF, arg(3)
            data = bytes(uc.mem_read(buf, n))
            if h == 2: res.stdout += data
            elif h == 3: res.stderr += data
            else: raise RuntimeError(f"WriteFile on an invalid handle {h}")
            uc.mem_write(pw, struct.pack("<I", n))
        elif name == "ReadFile":
            buf, n, pr = arg(1), arg(2) & 0xFFFFFFFF, arg(3)
            chunk = bytes(stdin_buf[:n]); del stdin_buf[:n]
            uc.mem_write(buf, chunk)
            uc.mem_write(pr, struct.pack("<I", len(chunk)))
        elif name == "GetProcessHeap":
            ret = 0xAAAA0000
        elif name == "HeapAlloc":
            if arg(0) != 0xAAAA0000: raise RuntimeError("HeapAlloc with an invalid heap")
            n = max(arg(2), 1)
            p = (heap["next"] + 15) & ~15
            heap["next"] = p + n + 16
            heap["blocks"][p] = n
            res.heap_live += n; res.heap_allocs += 1
            ret = p
        elif name == "HeapFree":
            p = arg(2)
            if p not in heap["blocks"]: raise RuntimeError(f"HeapFree of an invalid/duplicate pointer 0x{p:x}")
            res.heap_live -= heap["blocks"].pop(p); res.heap_frees += 1
        elif name == "SetConsoleOutputCP":
            ret = 1
        else:
            raise RuntimeError("API not simulated: " + name)
        uc.reg_write(UC_X86_REG_RAX, ret)
        ra = struct.unpack("<Q", uc.mem_read(rsp, 8))[0]
        uc.reg_write(UC_X86_REG_RSP, rsp + 8)
        uc.reg_write(UC_X86_REG_RIP, ra)

    err = []
    def hook_code(u, addr, size, ud):
        if addr in imports:
            try: api(imports[addr])
            except Exception as e:
                err.append(e); u.emu_stop()
    uc.hook_add(UC_HOOK_CODE, hook_code, begin=STUB_BASE, end=STUB_BASE + 0x1000)

    entry = base + pe.OPTIONAL_HEADER.AddressOfEntryPoint
    uc.reg_write(UC_X86_REG_RSP, STACK_TOP - 0x108)       # = 8 (mod 16), as on Windows
    try:
        uc.emu_start(entry, 0, count=max_insns)
    except UcError as e:
        rip = uc.reg_read(UC_X86_REG_RIP)
        code = bytes(uc.mem_read(rip, 16)) if True else b""
        md = Cs(CS_ARCH_X86, CS_MODE_64)
        dis = next(md.disasm(code, rip), None)
        res.error = f"UcError {e} em rip=0x{rip:x} ({dis.mnemonic + ' ' + dis.op_str if dis else '?'})"
    if err:
        res.error = str(err[0])
    if res.exit_code is None and res.error is None:
        res.error = "instruction limit reached (infinite loop?)"
    return res


if __name__ == "__main__":
    r = run_pe(sys.argv[1], sys.stdin.buffer.read() if len(sys.argv) > 2 else b"")
    sys.stdout.buffer.write(r.stdout)
    sys.stderr.buffer.write(r.stderr)
    if r.error: print("[emu] ERRO:", r.error, file=sys.stderr)
    print(f"[emu] exit={r.exit_code} insns={r.insns} heap_live={r.heap_live}B allocs={r.heap_allocs} frees={r.heap_frees}", file=sys.stderr)
    sys.exit(0 if r.exit_code == 0 else 1)
