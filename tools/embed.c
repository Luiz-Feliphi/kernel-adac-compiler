/* embed.c - turns .adac files into C string constants (used by the Makefile). */
#include <stdio.h>
#include <string.h>
int main(int argc, char **argv) {
    printf("/* GENERATED by tools/embed - do not edit */\n");
    for (int i = 1; i + 1 < argc; i += 2) {
        FILE *f = fopen(argv[i + 1], "rb");
        if (!f) { fprintf(stderr, "embed: could not open %s\n", argv[i + 1]); return 1; }
        printf("const char *%s =\n\"", argv[i]);
        int c;
        while ((c = fgetc(f)) != EOF) {
            if (c == '\n') printf("\\n\"\n\"");
            else if (c == '"' || c == '\\') printf("\\%c", c);
            else if (c == '\r') {}
            else if (c == '\t') printf("\\t");
            else putchar(c);
        }
        printf("\";\n");
        fclose(f);
    }
    return 0;
}
